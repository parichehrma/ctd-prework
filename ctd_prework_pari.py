# This program asks for the user's name and the temperature, then recommends what to wear:
name=input('What is your name? ')
temperature = float(input('What is the temperature in Fahrenheit? '))
if temperature>=80:
  print(name,'the temperature is', temperature, 'degrees. It is hot outside. Wear a T-shirt!')
elif temperature>=55:
  print(name,'the temperature is', temperature, 'degrees. It is mild outside. Wear a sweater!')
else:
  print(name,'the temperature is', temperature, 'degrees. It is cold outside. Wear a jacket!')

